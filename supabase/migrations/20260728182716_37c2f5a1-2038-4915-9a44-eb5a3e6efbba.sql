
CREATE TABLE public.cdi_daily (
  date DATE PRIMARY KEY,
  rate NUMERIC NOT NULL,
  factor NUMERIC NOT NULL,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
GRANT SELECT ON public.cdi_daily TO authenticated, anon;
GRANT ALL ON public.cdi_daily TO service_role;
ALTER TABLE public.cdi_daily ENABLE ROW LEVEL SECURITY;
CREATE POLICY "cdi_daily leitura pública" ON public.cdi_daily FOR SELECT USING (true);

CREATE TABLE public.holidays (
  date DATE PRIMARY KEY,
  name TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'anbima'
);
GRANT SELECT ON public.holidays TO authenticated, anon;
GRANT ALL ON public.holidays TO service_role;
ALTER TABLE public.holidays ENABLE ROW LEVEL SECURITY;
CREATE POLICY "holidays leitura pública" ON public.holidays FOR SELECT USING (true);

